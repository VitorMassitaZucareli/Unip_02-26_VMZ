print("Vamos Calcular a media da altura de 3 pessoas")
alt1=float(input("Digite a altura da primeira pessoa em centimetros: "))
alt2=float(input("Digite a altura da segunda pessoa em centimetros: "))
alt3=float(input("Digite a altura da terceira pessoa em centimetros: "))
altmedia=(alt1+alt2+alt3)/3
print(f"A altura media das tres pessoas é de {altmedia:0.2f} centimetros")